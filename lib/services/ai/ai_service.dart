import 'dart:convert';
import 'package:http/http.dart' as http;
import '../../core/errors/app_exception.dart';

abstract class AiService {
  Future<String> generateGroundedResponse({
    required String userPrompt,
    required String systemInstruction,
    required List<Map<String, dynamic>> contextData,
    required String modelName,
  });
}

/// Production implementation communicating with secure backend proxy or OpenRouter.
class OpenRouterAiService implements AiService {
  final String backendUrl;
  final String?
  clientApiKey; // Developer-provided key in settings if direct mode
  final http.Client _client;

  OpenRouterAiService({
    required this.backendUrl,
    this.clientApiKey,
    http.Client? client,
  }) : _client = client ?? http.Client();

  @override
  Future<String> generateGroundedResponse({
    required String userPrompt,
    required String systemInstruction,
    required List<Map<String, dynamic>> contextData,
    required String modelName,
  }) async {
    try {
      final messages = [
        {'role': 'system', 'content': systemInstruction},
        {
          'role': 'user',
          'content':
              'RELEVANT VEHICLE CONTEXT & KNOWLEDGE:\n${json.encode(contextData)}\n\nUSER QUESTION: $userPrompt',
        },
      ];

      // If a backend proxy is configured
      final uri = Uri.parse(backendUrl);
      final headers = <String, String>{'Content-Type': 'application/json'};

      if (clientApiKey != null && clientApiKey!.isNotEmpty) {
        headers['Authorization'] = 'Bearer $clientApiKey';
      }

      final body = json.encode({
        'model': modelName,
        'messages': messages,
        'temperature': 0.2, // Low temperature for high factual accuracy
      });

      final response = await _client
          .post(uri, headers: headers, body: body)
          .timeout(const Duration(seconds: 15));

      if (response.statusCode == 200) {
        final data = json.decode(response.body) as Map<String, dynamic>;
        final choices = data['choices'] as List<dynamic>?;
        if (choices != null && choices.isNotEmpty) {
          final first = choices.first as Map<String, dynamic>;
          final msg = first['message'] as Map<String, dynamic>?;
          return msg?['content'] as String? ?? 'No response content received.';
        }
        return 'No answer generated by model.';
      } else {
        throw AiServiceException(
          'AI service returned code ${response.statusCode}: ${response.body}',
        );
      }
    } catch (e) {
      if (e is AiServiceException) rethrow;
      throw AiServiceException('Connection to AI service failed: $e');
    }
  }
}
